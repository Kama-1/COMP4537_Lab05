CREATE SCHEMA IF NOT EXISTS COMP4537_Lab05;
USE COMP4537_Lab05;

CREATE TABLE IF NOT EXISTS patient (
	patientid INT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(100) NOT NULL,
    dateOfBirth DATETIME NOT NULL
);

CREATE USER IF NOT EXISTS readOnly@localhost
IDENTIFIED BY 'read';

CREATE USER IF NOT EXISTS insertOnly@localhost
IDENTIFIED BY 'insert';

GRANT SELECT ON COMP4537_Lab05.patient TO readOnly@localhost;

GRANT INSERT ON COMP4537_Lab05.patient TO insertOnly;
